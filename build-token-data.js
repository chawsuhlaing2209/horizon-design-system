// Emits resolved token data for the Storybook docs, one JSON file per
// collection/mode in the Figma manifest.
//
// Why this exists separately from build-tokens.js: the CSS build only ships the
// *web* space and type modes, and iOS/Android only ship mobile. Nothing ships
// back-office. The docs have to show every mode, so they read this instead of
// the built CSS. build-tokens.js is left alone — it owns the product artefacts,
// this owns the documentation.
//
// Each token is assembled from three sources, each authoritative for one job:
//   value      css-transformed  — a hex / px / box-shadow string, for rendering
//   typography resolved, untransformed structured value, for type specimens
//   cssOutput  read back out of build/tokens/css/*.css — literally what the build
//              emitted, so the docs can never misreport it

import StyleDictionary from 'style-dictionary';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';

const T = 'tokens/';
const CORE = T + 'core.value.tokens.json';
const OUT = 'build/tokens/json/';

// Figma writes weights as style names, and not always the way the CSS build
// expects ("Semi Bold" vs "SemiBold"). Docs normalise loosely so a specimen
// renders correctly whatever Figma wrote — deliberately more forgiving than
// build-tokens.js, whose stricter map is what the cssOutput column exposes.
const WEIGHTS = { thin: 100, extralight: 200, light: 300, regular: 400,
                  medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };
const weight = (w) => typeof w === 'number' ? w
  : WEIGHTS[String(w).toLowerCase().replace(/[\s_-]/g, '')] ?? w;

const dim = (d) => d == null ? null
  : typeof d === 'object' ? `${d.value}${d.unit ?? 'px'}` : `${d}px`;

const typographyCss = (v) => ({
  fontFamily: v.fontFamily,
  fontWeight: weight(v.fontWeight),
  fontSize: dim(v.fontSize),
  lineHeight: dim(v.lineHeight),
  letterSpacing: dim(v.letterSpacing),
});

/** Read a built stylesheet back as a map of custom property -> emitted value. */
const readCss = (path) => {
  const map = new Map();
  let css = '';
  try { css = readFileSync(path, 'utf8'); }
  catch { return map; } // Not built yet; docs fall back to "not shipped".
  for (const [, name, val] of css.matchAll(/^\s*--([\w-]+):\s*([^;]+);/gm)) {
    map.set(name, val.trim());
  }
  return map;
};

const cssLight = readCss('build/tokens/css/tokens.css');
const cssDark = readCss('build/tokens/css/tokens-dark.css');

/**
 * tokens.css declares the light values under `:root` only, so a `[data-theme]`
 * subtree can go dark but can never come back to light. The docs show both
 * modes on one page, so they need an explicit light block. Re-emit the exact
 * declarations tokens.css already contains under a `[data-theme="light"]`
 * selector — generated, never hand-written, so it cannot drift from the build.
 *
 * Docs-only. The product stylesheet is not touched.
 */
const writeLightThemeBlock = () => {
  if (!cssLight.size) return;
  const body = [...cssLight].map(([name, value]) => `  --${name}: ${value};`).join('\n');
  writeFileSync('build/tokens/css/docs-theme-light.css',
    `/* Generated by build-token-data.js. Docs only — do not import in a product. */\n` +
    `[data-theme="light"] {\n${body}\n}\n`);
};

const platformTokens = (source, platform) =>
  new StyleDictionary({ source, platforms: { p: platform } }).getPlatformTokens('p');

/**
 * @param destination file to write into build/tokens/json/
 * @param source      style-dictionary sources; core is included so aliases resolve
 * @param filter      keep only tokens authored in the collection's own file
 * @param cssFrom     which built stylesheet this collection's vars come from
 */
const write = async (destination, source, filter = () => true, cssFrom = cssLight) => {
  // Structured and fully reference-resolved — what specimens need.
  const resolved = await platformTokens(source, { transforms: ['name/kebab'] });
  // css-transformed — hex, px, box-shadow strings for rendering.
  const styled = await platformTokens(source, { transformGroup: 'css' });
  const styledBy = new Map(styled.allTokens.map((t) => [t.name, t]));

  const rows = resolved.allTokens.filter(filter).map((t) => {
    const type = t.$type ?? t.type;
    const original = t.original?.$value ?? t.original?.value;
    const resolvedValue = t.$value ?? t.value;
    const row = {
      name: t.name,
      cssVar: `--${t.name}`,
      type,
      description: t.$description ?? t.description ?? '',
      alias: typeof original === 'string' && original.startsWith('{') ? original : null,
      // What build/tokens/css actually emitted, or null when this mode never reaches CSS.
      cssOutput: cssFrom.get(t.name) ?? null,
    };
    if (type === 'typography') row.typography = typographyCss(resolvedValue);
    else if (type === 'shadow') {
      row.layers = resolvedValue;
      row.value = styledBy.get(t.name)?.$value ?? null;
    } else row.value = styledBy.get(t.name)?.$value ?? null;
    return row;
  });

  writeFileSync(OUT + destination, JSON.stringify(rows, null, 2) + '\n');
  return rows.length;
};

const only = (file) => (t) => t.filePath.includes(file);

mkdirSync(OUT, { recursive: true });
let total = 0;

total += await write('core.json', [CORE]);

for (const mode of ['light', 'dark']) {
  const file = `semantic-color.${mode}.tokens.json`;
  total += await write(`semantic-color.${mode}.json`, [CORE, T + file], only(file),
    mode === 'dark' ? cssDark : cssLight);
}

for (const mode of ['web', 'mobile', 'back-office']) {
  const space = `semantic-space.${mode}.tokens.json`;
  const type = `type.${mode}.tokens.json`;
  // Only the web mode is in the stylesheet; the others correctly report null.
  const from = mode === 'web' ? cssLight : new Map();
  total += await write(`semantic-space.${mode}.json`, [CORE, T + space], only(space), from);
  total += await write(`type.${mode}.json`, [CORE, T + type], only(type), from);
}

total += await write('typography.styles.json',
  [T + 'type.web.tokens.json', T + 'typography.styles.tokens.json'], only('typography.styles'));
total += await write('effects.styles.json', [T + 'effects.styles.tokens.json']);

writeLightThemeBlock();

console.log(`token data: ${total} tokens -> ${OUT}`);
